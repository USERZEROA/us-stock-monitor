#!/usr/bin/env python3
"""
Historical win-rate lookup from calibration data.

Reads cached CSV files from research/calibration/ (generated by
fetch_calibration_data.py) and computes empirical win rates for different
VIX regimes and time horizons.

Usage:
    python3 scripts/probability_lookup.py [--ticker MSFT] [--vix 19.5]

Outputs JSON with P(up) at 1d/5d/10d/20d for each VIX regime, plus
regime-specific summary for the provided current VIX.

No network required — uses cached calibration CSVs only.
"""
from __future__ import annotations

import argparse
import json
from datetime import datetime
from pathlib import Path
from typing import Optional

ROOT = Path(__file__).resolve().parents[1]
CALIB_DIR = ROOT / "research" / "calibration"

try:
    import pandas as pd
    HAS_PANDAS = True
except ImportError:
    HAS_PANDAS = False


def load_series(csv_path: Path, col: Optional[str] = None) -> "pd.Series":
    """Load a pandas Series from a calibration CSV file."""
    if not HAS_PANDAS:
        raise ImportError("pandas required: pip3 install pandas --break-system-packages")
    df = pd.read_csv(csv_path, index_col=0, parse_dates=True)
    if col and col in df.columns:
        return df[col].dropna()
    # For single-column series files saved with .to_csv()
    return df.iloc[:, 0].dropna()


def compute_win_rates(
    price_series: "pd.Series",
    vix_series: "pd.Series",
    horizons: list[int] = [1, 5, 10, 20],
) -> dict:
    """
    Compute P(forward return > 0) for each VIX regime and time horizon.

    Parameters
    ----------
    price_series : pd.Series — daily close prices (Date index)
    vix_series : pd.Series — VIX daily close (Date index)
    horizons : list[int] — forward return periods in trading days

    Returns
    -------
    dict mapping horizon → regime → {win_rate, n, median_return_pct, mean_return_pct}
    """
    import pandas as pd  # already imported via HAS_PANDAS check

    combined = pd.DataFrame({
        "price": price_series,
        "vix": vix_series,
    }).dropna()

    # Compute forward returns for each horizon
    for h in horizons:
        combined[f"fwd{h}"] = combined["price"].shift(-h) / combined["price"] - 1

    regimes = [
        ("vix_below_18", combined["vix"] < 18),
        ("vix_18_20", (combined["vix"] >= 18) & (combined["vix"] < 20)),
        ("vix_above_20", combined["vix"] >= 20),
        ("vix_above_25", combined["vix"] >= 25),
        ("vix_above_30", combined["vix"] >= 30),
    ]

    results = {}
    for h in horizons:
        col = f"fwd{h}"
        results[f"fwd_{h}d"] = {}
        for regime_name, mask in regimes:
            subset = combined.loc[mask, col].dropna()
            if len(subset) < 20:
                results[f"fwd_{h}d"][regime_name] = None
                continue
            results[f"fwd_{h}d"][regime_name] = {
                "win_rate": round(float((subset > 0).mean()), 4),
                "n_observations": int(len(subset)),
                "median_return_pct": round(float(subset.median() * 100), 3),
                "mean_return_pct": round(float(subset.mean() * 100), 3),
                "p5_return_pct": round(float(subset.quantile(0.05) * 100), 3),
                "p95_return_pct": round(float(subset.quantile(0.95) * 100), 3),
            }
    return results


def current_regime(vix: float) -> str:
    if vix < 18:
        return "vix_below_18"
    elif vix < 20:
        return "vix_18_20"
    elif vix < 25:
        return "vix_above_20"
    elif vix < 30:
        return "vix_above_25"
    else:
        return "vix_above_30"


def regime_label(regime: str) -> str:
    labels = {
        "vix_below_18": "VIX < 18 (open gate)",
        "vix_18_20": "VIX 18-20 (reduced gate)",
        "vix_above_20": "VIX > 20 (paused gate)",
        "vix_above_25": "VIX > 25 (elevated stress)",
        "vix_above_30": "VIX > 30 (crisis regime)",
    }
    return labels.get(regime, regime)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Historical win-rate lookup from calibration CSVs"
    )
    parser.add_argument("--ticker", default="SPY",
                        help="Ticker to look up (SPY by default; must have CSV in calibration/)")
    parser.add_argument("--vix", type=float, default=None,
                        help="Current VIX level for regime summary")
    parser.add_argument("--horizons", default="1,5,10,20",
                        help="Comma-separated forward return horizons in days")
    args = parser.parse_args()

    if not HAS_PANDAS:
        print(json.dumps({"error": "pandas not installed", "install": "pip3 install pandas --break-system-packages"}))
        return

    ticker = args.ticker.upper()
    horizons = [int(h) for h in args.horizons.split(",")]

    # Load VIX
    vix_path = CALIB_DIR / "vix_history.csv"
    if not vix_path.exists():
        print(json.dumps({"error": f"VIX CSV not found. Run: python3 scripts/fetch_calibration_data.py"}))
        return
    try:
        vix_df = __import__("pandas").read_csv(vix_path, index_col=0, parse_dates=True)
        if "Close" in vix_df.columns:
            vix_series = vix_df["Close"].dropna()
        else:
            vix_series = vix_df.iloc[:, 0].dropna()
    except Exception as e:
        print(json.dumps({"error": f"Failed to load VIX: {e}"}))
        return

    # Load ticker price
    ticker_csv = CALIB_DIR / f"{ticker.lower()}_history.csv"
    if not ticker_csv.exists():
        print(json.dumps({
            "error": f"No calibration CSV for {ticker}",
            "available": [p.stem.replace("_history", "").upper()
                          for p in CALIB_DIR.glob("*_history.csv")],
        }))
        return
    try:
        price_series = load_series(ticker_csv)
    except Exception as e:
        print(json.dumps({"error": f"Failed to load {ticker}: {e}"}))
        return

    # Compute win rates
    win_rates = compute_win_rates(price_series, vix_series, horizons)

    # Determine current regime summary
    current_vix = args.vix
    regime_summary = None
    if current_vix is not None:
        regime = current_regime(current_vix)
        regime_summary = {
            "current_vix": current_vix,
            "current_regime": regime,
            "regime_label": regime_label(regime),
            "win_rates_in_current_regime": {},
        }
        for fwd_key, regime_data in win_rates.items():
            if regime_data and regime in regime_data and regime_data[regime]:
                regime_summary["win_rates_in_current_regime"][fwd_key] = \
                    regime_data[regime]["win_rate"]

    result = {
        "ticker": ticker,
        "generated_at": datetime.now().strftime("%Y-%m-%d %H:%M ET"),
        "data_source": str(ticker_csv),
        "historical_win_rates_by_vix_regime": win_rates,
        "current_regime_summary": regime_summary,
        "interpretation": (
            "These are historical P(close > 0) rates over the stated horizon "
            "when VIX was in each regime at the start of the holding period. "
            "Use as a base-rate prior for Kelly calculations — not a guarantee. "
            "Individual stock win rates diverge from index win rates."
        ),
    }

    output_str = json.dumps(result, indent=2, ensure_ascii=False)
    print(output_str)

    # Save for reports to read
    out_path = ROOT / f"probability_lookup_{ticker.lower()}.json"
    out_path.write_text(output_str, encoding="utf-8")
    print(f"\n[Saved to {out_path}]", flush=True)


if __name__ == "__main__":
    main()
